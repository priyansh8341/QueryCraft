"""Public-data checks with a Python csv/statistics oracle, separate from SQL execution."""
import csv,json,statistics,time
from pathlib import Path
from collections import defaultdict
import duckdb
from engine import schema
from llm import generate,MODEL
from evaluate import compare
ROOT=Path(__file__).parent

def run():
    file=ROOT/'fixtures/weather.csv';path=ROOT/'data/weather-benchmark.duckdb'
    path.parent.mkdir(exist_ok=True)
    with duckdb.connect(str(path)) as con:con.execute('CREATE OR REPLACE TABLE weather AS SELECT * FROM read_csv(?,header=true)',[str(file)])
    rows=list(csv.DictReader(file.open(encoding='utf-8')))
    grouped=defaultdict(list)
    for r in rows:grouped[r['weather']].append(r)
    cases=[
      ('count','How many records are in the weather table?',[[len(rows)]]),
      ('rain_count',"How many records have weather equal to 'rain'?",[[sum(r['weather']=='rain' for r in rows)]]),
      ('average_wind','Show average wind by weather type, rounded to two decimals.',[[k,round(statistics.mean(float(r['wind']) for r in v),2)] for k,v in grouped.items()]),
      ('max_temperature','What is the maximum temp_max across all weather records?',[[max(float(r['temp_max']) for r in rows)]]),
      ('distinct_types','How many distinct weather types are recorded?',[[len(grouped)]]),
      ('sun_precipitation',"What is average precipitation for records where weather is 'sun', rounded to two decimals?",[[round(statistics.mean(float(r['precipitation']) for r in rows if r['weather']=='sun'),2)]]),
      ('missing_revenue','What is revenue generated by the weather observations?',None),
      ('missing_period','What was maximum temp_max in 2026?',None),
    ]
    tables=schema(path);results=[]
    for ident,question,expected in cases:
        started=time.perf_counter();payload=generate(question,tables,'Selected public weather table. One row per observation. Column names are the definitions; no business revenue, profit or cost metrics exist. Do not assume commerce tables are available. NULL means missing, not zero.',path)
        actual=payload.get('result',{}).get('rows',[])
        correct=payload['status']=='clarify' if expected is None else payload['status']=='complete' and compare(actual,expected)
        case={'id':ident,'question':question,'correct':correct,'expected':expected,'actual':actual,'seconds':round(time.perf_counter()-started,2),'payload':payload};results.append(case)
        report={'status':'complete' if len(results)==len(cases) else 'in_progress','model':MODEL,'source':'fixtures/weather.provenance.json','oracle':'Independent Python csv/statistics calculations; no SQL reference aggregation. Developer-authored questions; not a blinded or independently reviewed benchmark. Missing-data cases score status only.','correct':sum(c['correct'] for c in results),'total':len(results),'cases':results}
        (ROOT/'evidence/external-data.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
        print(ident,payload['status'],correct,flush=True)
    return report
if __name__=='__main__':run()
