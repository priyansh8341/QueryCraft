TABLES=[{'columns':[{'name':'revenue_aed'},{'name':'refund_aed'}],'date_ranges':{'order_date':['2025-01-01','2025-12-31']}}]
def test_missing_capabilities_and_ambiguity():
    assert capability_gap('profit margin by product',TABLES)
    assert capability_gap('return on advertising spend',TABLES)
    assert capability_gap('Which customers are best?',TABLES)
    assert capability_gap('Revenue in March 2026',TABLES)
    assert capability_gap('Completed revenue by product in 2025',TABLES) is None
    assert capability_gap('average shipping delivery duration in days',TABLES)
    mixed=[dict(TABLES[0],name='orders'),{'columns':[], 'name':'refunds','date_ranges':{'refund_date':['2025-01-02','2026-01-08']}}]
    assert capability_gap('Revenue in March 2026',mixed)
    enriched=TABLES+[{'columns':[{'name':'cost_aed'},{'name':'ad_spend'}]}]
    assert capability_gap('profit margin by product',enriched) is None

def test_grain_contract_rejects_missing_dimension():
    with pytest.raises(QueryError):check_dimensions('How many completed orders per channel?',{'columns':['order_count']})
    check_dimensions('How many completed orders per channel?',{'columns':['channel','order_count']})
    check_dimensions('Revenue by customer country',{'columns':['country','revenue_aed']})
    check_dimensions('Revenue by product category',{'columns':['category','revenue_aed']})

