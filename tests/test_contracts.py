def test_reference_comparison_detects_semantic_errors():
    assert compare([['a',10.001],['b',5]],[['b',5],['a',10]])
    assert not compare([['a',10]],[['a',11]])
    assert not compare([['a',10],['a',10]],[['a',10]])
    assert not compare([[10,'a']],[['a',10]])
    assert compare([['2025-01-01T00:00:00',2]],[['2025-01-01',2]])

def test_quarter_vs_month_regression():
    with pytest.raises(QueryError):check_temporal_grain('Compare Q3 and Q4 revenue',"SELECT SUM(CASE WHEN EXTRACT(MONTH FROM order_date)=7 THEN revenue_aed ELSE 0 END) FROM completed_sales")
    check_temporal_grain('Compare Q3 and Q4 revenue',"SELECT SUM(CASE WHEN EXTRACT(QUARTER FROM order_date)=3 THEN revenue_aed ELSE 0 END) FROM completed_sales")
    check_temporal_grain('Revenue in the first month of Q3',"SELECT SUM(revenue_aed) FROM completed_sales WHERE MONTH(order_date)=7")

def test_missing_measure_does_not_inherit_commerce_definitions():
    tables=[{'name':'weather','columns':[{'name':'precipitation'},{'name':'wind'}]}]
    assert capability_gap('What is revenue generated by weather?',tables)
    assert capability_gap('What is average wind?',tables) is None

def test_group_labels_and_rounding_contract():
    with pytest.raises(QueryError):check_projection_contract('Average wind by weather type, two decimals','SELECT round(avg(wind)) FROM weather GROUP BY weather')
    check_projection_contract('Average wind by weather type, two decimals','SELECT weather,round(avg(wind),2) FROM weather GROUP BY weather')
